"""Recipe -> standalone Python script that rebuilds the part in Inventor.

The script carries the runtime (inventor_runtime.py) and a PLAN: user
parameters in dependency order plus a list of operations whose dimensions are
Inventor expressions bound to those parameters.
"""

from __future__ import annotations

import pprint
from pathlib import Path

from ..expr import evaluate, names_in
from ..recipe import Recipe, RecipeError, placement_exprs, placement_points
from ..standards import THREAD, hole_geometry

# names Inventor would read as units inside expressions
_RESERVED = {"in", "ft", "m", "cm", "mm", "um", "deg", "rad", "ul", "s", "g", "kg"}


def _ordered_parameters(params: dict) -> list[tuple[str, str]]:
    done: list[str] = []

    def visit(name: str) -> None:
        if name in done:
            return
        for dep in sorted(names_in(params[name])):
            visit(dep)
        done.append(name)

    for name in params:
        if name.lower() in _RESERVED:
            raise RecipeError(f"parameter name {name!r} clashes with an Inventor unit")
        visit(name)
    return [(n, str(params[n])) for n in done]


def _mm(value: float) -> str:
    return f"{value:g} mm"


def plan(recipe: Recipe) -> dict:
    env = recipe.env()
    plate = recipe.plate
    ops: list[dict] = [{
        "op": "plate",
        "width": str(plate["width"]),
        "depth": str(plate["depth"]),
        "thickness": str(plate["thickness"]),
        "width_value": evaluate(plate["width"], env),
        "depth_value": evaluate(plate["depth"], env),
    }]
    if plate.get("corners"):
        ops.append({"op": "corners", "corner_type": plate["corners"]["type"],
                    "size": str(plate["corners"]["size"])})

    for i, feat in enumerate(recipe.features[1:], start=1):
        fid = feat.get("id", f"feature_{i}")
        depth = feat.get("depth", "through")
        depth = "through" if depth == "through" else str(depth)
        if feat["type"] == "hole":
            spec = feat["spec"]
            geo = hole_geometry(spec, env)
            op = {"op": "holes", "id": fid, "depth": depth,
                  "points": _inventor_points(feat["at"], env),
                  "values": placement_points(feat["at"], env),
                  "diameter": str(spec["diameter"]) if spec["kind"] == "plain"
                  else _mm(geo.diameter)}
            if spec["kind"] == "tapped":
                op["thread"] = f"{spec['size']}x{THREAD[spec['size']][0]:g}"
            if geo.cbore_diameter:
                op["cbore_diameter"] = _mm(geo.cbore_diameter)
                op["cbore_depth"] = _mm(geo.cbore_depth)
            ops.append(op)
        else:
            cx, cy = (evaluate(v, env) for v in feat["center"])
            if feat["type"] == "pocket":
                length, width = (evaluate(v, env) for v in feat["size"])
                r = evaluate(feat.get("corner_radius", 0), env)
            else:
                length, width = evaluate(feat["length"], env), evaluate(feat["width"], env)
                r = width / 2
            angle = evaluate(feat.get("angle", 0), env)
            if angle % 90:
                raise RecipeError(f"{fid}: only 0/90/180/270 degree outlines in v0.1")
            ops.append({"op": "profile_cut", "id": fid, "depth": depth, "cx": cx,
                        "cy": cy, "length": length, "width": width, "r": r,
                        "angle": angle})
    return {"name": recipe.name,
            "parameters": _ordered_parameters(recipe.parameters),
            "operations": ops}


def _inventor_points(at: dict, env: dict) -> list[list[str]]:
    if "circle" not in at:
        return [list(p) for p in placement_exprs(at, env)]
    # Inventor trig functions take angles with units
    c = at["circle"]
    (cx, cy), r = c["center"], c["radius"]
    n = round(evaluate(c["count"], env))
    start = evaluate(c.get("start_angle", 0), env)
    out = []
    for i in range(n):
        ang = f"{start + i * 360 / n:g} deg"
        out.append([f"({cx}) + ({r}) * cos({ang})", f"({cy}) + ({r}) * sin({ang})"])
    return out


def write_script(recipe: Recipe, path: str | Path) -> Path:
    runtime = (Path(__file__).parent / "inventor_runtime.py").read_text(encoding="utf-8")
    body = pprint.pformat(plan(recipe), width=100, sort_dicts=False)
    path = Path(path)
    path.write_text(
        f"{runtime}\n\n# ---- generated by cadrecipe from recipe '{recipe.name}' ----\n"
        f"PLAN = {body}\n\nif __name__ == \"__main__\":\n    main(PLAN)\n",
        encoding="utf-8",
    )
    return path
